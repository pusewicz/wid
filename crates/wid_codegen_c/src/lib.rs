fn local_name(local: &ir::Local, id: LocalId) -> String {
    match local.name {
        Some(n) => format!("{}_{}", sanitize(n.as_str()), id.0),
        None => format!("t_{}", id.0),
    }
}

fn sanitize(name: &str) -> String {
    name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect()
}

fn c_binop(op: ir::BinaryOp) -> &'static str {
    use ir::BinaryOp as B;
    match op {
        B::Add => "+",
        B::Sub => "-",
        B::Mul => "*",
        B::Div => "/",
        B::Rem => "%",
        B::BitAnd => "&",
        B::BitOr => "|",
        B::BitXor => "^",
        B::Shl => "<<",
        B::Shr => ">>",
        B::Eq => "==",
        B::Ne => "!=",
        B::Lt => "<",
        B::Le => "<=",
        B::Gt => ">",
        B::Ge => ">=",
        B::And => "&&",
        B::Or => "||",
        B::Pow => "**",
        B::Cmp => "<=>",
    }
}

/// Removes one layer of redundant outer parentheses. Parentheses around a
/// comma expression are kept, since removing them would split it.
fn strip_parens(s: &str) -> &str {
    let bytes = s.as_bytes();
    if bytes.first() != Some(&b'(') || bytes.last() != Some(&b')') {
        return s;
    }
    let mut depth = 0i32;
    let mut quote: Option<u8> = None;
    let mut escaped = false;
    for (i, &b) in bytes.iter().enumerate() {
        if let Some(q) = quote {
            if escaped {
                escaped = false;
            } else if b == b'\\' {
                escaped = true;
            } else if b == q {
                quote = None;
            }
            continue;
        }
        match b {
            b'"' | b'\'' => quote = Some(b),
            b'(' | b'{' | b'[' => depth += 1,
            b',' if depth == 1 => return s,
            b')' | b'}' | b']' => {
                depth -= 1;
                if depth == 0 && i != bytes.len() - 1 {
                    return s;
                }
            }
            _ => {}
        }
    }
    &s[1..s.len() - 1]
}

/// The name generated C calls a function by: the alias of an `@[extern]`
/// function no header declares, the C name of one a header does, or the
/// exported or internal name of a Wid function.
fn call_name(f: &ir::Function) -> String {
    match (&f.foreign, &f.c_call) {
        (Some(symbol), None) if !symbol.starts_with("wid_") => extern_alias(symbol),
        (Some(symbol), _) => symbol.clone(),
        (None, _) => f.export.clone().unwrap_or_else(|| f.c_name.clone()),
    }
}

/// The C name an `@[extern]` function is declared under.
fn extern_alias(symbol: &str) -> String {
    let safe: String = symbol.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    format!("wid_extern_{safe}")
}

/// Formats bytes as a C string literal.
pub fn c_string_literal(bytes: &[u8]) -> String {
    let mut out = String::from("\"");
    for &b in bytes {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\t' => out.push_str("\\t"),
            b'\r' => out.push_str("\\r"),
            0x20..=0x7e => out.push(b as char),
            _ => {
                let _ = write!(out, "\\{:03o}", b);
            }
        }
    }
    out.push('"');
    out
}

fn float_literal(v: f64, kind: FloatTy) -> String {
    if v.is_nan() {
        return "NAN".into();
    }
    if v.is_infinite() {
        return if v < 0.0 { "(-INFINITY)".into() } else { "INFINITY".into() };
    }
    match kind {
        FloatTy::F32 => {
            let mut s = format!("{:?}", v as f32);
            if !s.contains(['.', 'e', 'E']) {
                s.push_str(".0");
            }
            format!("{s}f")
        }
        FloatTy::F64 => {
            let mut s = format!("{v:?}");
            if !s.contains(['.', 'e', 'E']) {
                s.push_str(".0");
            }
            s
        }
    }
}

fn visit_block(block: &ir::Block, f: &mut impl FnMut(&ir::Expr)) {
    for s in &block.stmts {
        visit_stmt(s, f);
    }
}

fn visit_stmt(stmt: &Stmt, f: &mut impl FnMut(&ir::Expr)) {
    match stmt {
        Stmt::Let { init: Some(e), .. } | Stmt::Expr(e) | Stmt::Return(Some(e)) => visit_expr(e, f),
        Stmt::Assign { target, value } => {
            visit_expr(target, f);
            visit_expr(value, f);
        }
        Stmt::If { cond, then, else_ } => {
            visit_expr(cond, f);
            visit_block(then, f);
            visit_block(else_, f);
        }
        Stmt::Loop { body, .. } | Stmt::Labeled { body, .. } | Stmt::Scope(body) | Stmt::WithContext(body) => {
            visit_block(body, f)
        }
        _ => {}
    }
}

fn visit_expr(e: &ir::Expr, f: &mut impl FnMut(&ir::Expr)) {
    f(e);
    match &e.kind {
        ExprKind::Field { base, .. } => visit_expr(base, f),
        ExprKind::Deref(x)
        | ExprKind::AddrOf(x)
        | ExprKind::Unary { expr: x, .. }
        | ExprKind::Cast { expr: x, .. }
        | ExprKind::OptSome(x)
        | ExprKind::OptIsSome(x)
        | ExprKind::OptGet(x)
        | ExprKind::UnionTag(x)
        | ExprKind::UnionWrap { value: x, .. }
        | ExprKind::UnionGet { value: x, .. } => visit_expr(x, f),
        ExprKind::Index { base, index, .. } => {
            visit_expr(base, f);
            visit_expr(index, f);
        }
        ExprKind::SliceOf { base, lo, hi, .. } => {
            visit_expr(base, f);
            visit_expr(lo, f);
            visit_expr(hi, f);
        }
        ExprKind::Call { args, .. } | ExprKind::Builtin { args, .. } | ExprKind::Aggregate(args) => {
            for a in args {
                visit_expr(a, f);
            }
        }
        ExprKind::CallIndirect { callee, args, .. } => {
            visit_expr(callee, f);
            for a in args {
                visit_expr(a, f);
            }
        }
        ExprKind::Binary { lhs, rhs, .. } => {
            visit_expr(lhs, f);
            visit_expr(rhs, f);
        }
        ExprKind::Select { cond, then, else_ } => {
            visit_expr(cond, f);
            visit_expr(then, f);
            visit_expr(else_, f);
        }
        _ => {}
    }
}

fn collect_gotos(block: &ir::Block, out: &mut HashSet<LabelId>) {
    for s in &block.stmts {
        match s {
            Stmt::Goto(l) => {
                out.insert(*l);
            }
            Stmt::If { then, else_, .. } => {
                collect_gotos(then, out);
                collect_gotos(else_, out);
            }
            Stmt::Loop { body, .. } | Stmt::Labeled { body, .. } | Stmt::Scope(body) | Stmt::WithContext(body) => {
                collect_gotos(body, out)
            }
            _ => {}
        }
    }
}

/// Collects locals that are read somewhere (not merely assigned). Writing
/// a field or an element of a local stored in place (`a_0.data[i] = v`)
/// doesn't read it, and gcc reports a local or parameter that is only
/// written as "set but not used".
fn collect_reads(block: &ir::Block, types: &TypeTable, out: &mut HashSet<LocalId>) {
    for s in &block.stmts {
        collect_reads_stmt(s, types, out);
    }
}

fn collect_reads_stmt(stmt: &Stmt, types: &TypeTable, out: &mut HashSet<LocalId>) {
    let add = |e: &ir::Expr, out: &mut HashSet<LocalId>| {
        visit_expr(e, &mut |x| {
            if let ExprKind::Local(l) = x.kind {
                out.insert(l);
            }
        })
    };
    match stmt {
        Stmt::Let { init: Some(e), .. } | Stmt::Expr(e) | Stmt::Return(Some(e)) => add(e, out),
        Stmt::Assign { target, value } => {
            if target.written_local(types).is_some() {
                // Only the indexes on the way to the local are read.
                let mut place = target;
                loop {
                    match &place.kind {
                        ExprKind::Field { base, .. }
                        | ExprKind::OptGet(base)
                        | ExprKind::UnionGet { value: base, .. } => place = base,
                        ExprKind::Index { base, index, .. } => {
                            add(index, out);
                            place = base;
                        }
                        _ => break,
                    }
                }
            } else {
                add(target, out);
            }
            add(value, out);
        }
        Stmt::If { cond, then, else_ } => {
            add(cond, out);
            collect_reads(then, types, out);
            collect_reads(else_, types, out);
        }
        Stmt::Loop { body, .. } | Stmt::Labeled { body, .. } | Stmt::Scope(body) | Stmt::WithContext(body) => {
            collect_reads(body, types, out)
        }
        _ => {}
    }
}
